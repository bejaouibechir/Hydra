const { chromium } = require('C:/Users/DELL/Desktop/hydra-site/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  for (const tool of ['dlt','talend','dbt','airbyte','meltano','airflow','kestra','flowman','dagster']) {
    await page.goto(`http://localhost:4322/migrate/${tool}/`);
    await page.locator('#tab-simulator').click();
    const rival = page.locator('.sim-rival-code');
    const hydra = page.locator('.sim-hydra-code');
    await rival.click({ button: 'right' });
    const left = await page.locator('[data-context-menu] button').allTextContents();
    if (!left.includes('Explain this line') || !left.includes('Ignore this line')) throw new Error(`${tool}: left menu missing`);
    await page.locator('[data-context-menu] button', { hasText: 'Explain this line' }).click();
    if (!(await page.locator('[data-popover]').isVisible())) throw new Error(`${tool}: left explanation missing`);
    await page.locator('[data-popover-close]').click();
    await hydra.click({ button: 'right' });
    const right = await page.locator('[data-context-menu] button').allTextContents();
    if (!right.includes('Preview on sample data') || !right.includes('Show provenance')) throw new Error(`${tool}: right menu missing`);
    await page.locator('[data-context-menu] button', { hasText: 'Validate sample structure' }).click();
    if (!(await page.locator('[data-popover]').isVisible())) throw new Error(`${tool}: validation missing`);
    await page.locator('[data-popover-close]').click();
    await page.locator('[data-pane-menu="rival"]').click();
    if (!(await page.locator('[data-context-menu]').isVisible())) throw new Error(`${tool}: source button menu missing`);
    await page.keyboard.press('Escape');
    await page.locator('[data-pane-menu="hydra"]').click();
    if (!(await page.locator('[data-context-menu]').isVisible())) throw new Error(`${tool}: Hydra button menu missing`);
    await page.locator('[data-context-menu] button', { hasText: 'Expand this pane / restore both' }).click();
    if (!(await page.locator('[data-migrate-simulator]').evaluate(node => node.classList.contains('sim-expand-hydra')))) throw new Error(`${tool}: expand failed`);
    await page.locator('[data-pane-menu="hydra"]').click();
    await page.locator('[data-context-menu] button', { hasText: 'Expand this pane / restore both' }).click();
    if (await page.locator('[data-migrate-simulator]').evaluate(node => node.classList.contains('sim-expand-hydra'))) throw new Error(`${tool}: restore panes failed`);
    await page.locator('[data-pane-menu="rival"]').click();
    await page.locator('[data-context-menu] button', { hasText: 'Ignore this line' }).click();
    if (!(await page.locator('[data-toast]').textContent()).includes('1 source line')) throw new Error(`${tool}: ignore failed`);
    await page.locator('[data-pane-menu="rival"]').click();
    await page.locator('[data-context-menu] button', { hasText: 'Restore all ignored lines' }).click();
    await page.locator('[data-pane-menu="hydra"]').click();
    await page.locator('[data-context-menu] button', { hasText: 'Preview on sample data' }).click();
    if (!(await page.locator('[data-results]').isVisible())) throw new Error(`${tool}: preview failed`);
    await page.locator('[data-close]').click();
    await page.locator('[data-sim-action="source-check"]').click();
    if (!(await page.locator('[data-popover]').isVisible())) throw new Error(`${tool}: source icon failed`);
    await page.locator('[data-popover-close]').click();
    await page.locator('[data-sim-action="hydra-provenance"]').click();
    if (!(await page.locator('[data-popover]').isVisible())) throw new Error(`${tool}: provenance icon failed`);
    await page.locator('[data-popover-close]').click();
    if (tool === 'dbt') {
      await rival.fill((await rival.inputValue()).replace('amount > 50', 'amount > 125'));
      if (!(await hydra.inputValue()).includes('amount > 125')) throw new Error('Source to Hydra threshold sync failed');
      await hydra.fill((await hydra.inputValue()).replace('amount > 125', 'amount > 75'));
      if (!(await rival.inputValue()).includes('amount > 75')) throw new Error('Hydra to source threshold sync failed');
      await rival.evaluate(node => { const pos = node.value.indexOf('where amount >'); node.setSelectionRange(pos, pos); });
      await page.locator('[data-pane-menu="rival"]').click();
      await page.locator('[data-context-menu] button', { hasText: 'Ignore this line' }).click();
      if ((await hydra.inputValue()).includes('- filter:')) throw new Error('Mapped filter was not ignored');
      await page.locator('[data-pane-menu="rival"]').click();
      await page.locator('[data-context-menu] button', { hasText: 'Restore all ignored lines' }).click();
      if (!(await hydra.inputValue()).includes('- filter:')) throw new Error('Mapped filter was not restored');
      await rival.evaluate(node => { const pos = node.value.indexOf('where amount >'); node.setSelectionRange(pos, pos + 'where amount > 75'.length); });
      await page.locator('[data-pane-menu="rival"]').click();
      await page.locator('[data-context-menu] button', { hasText: 'Translate the selection only' }).click();
      if ((await hydra.inputValue()).includes('- aggregate:') || !(await hydra.inputValue()).includes('- filter:')) throw new Error('Selected translation did not rebuild steps');
      await page.locator('[data-pane-menu="rival"]').click();
      await page.locator('[data-context-menu] button', { hasText: 'Restore all ignored lines' }).click();
    }
    await page.keyboard.press('Escape');
    console.log(`${tool}: menus, toolbar, explanation, validation, expand, ignore, restore, preview OK`);
  }
  if (errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`);
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
